package xnpu

import chisel3._
import chisel3.util._
import chisel3.experimental.IntParam


// One DTCM bank: a byte-enabled true dual-port RAM with registered read data.
//
// This is hand-written rather than a SyncReadMem because Vivado will not infer
// block RAM from what firtool emits for a two-readWrite-port Chisel memory (two
// write always-blocks plus a registered-address / asynchronous-array read). An
// out-of-context run on xczu9eg put the whole 512 KiB into fabric: the DTCM
// appeared in neither the block-RAM nor the distributed-RAM report, and the RTL
// statistics showed ~1.05M 8-bit muxes (two per DTCM byte). The single-port ITCM
// infers fine from the same style, so it is specifically the second write port
// that inference rejects.
//
// Registering the output rather than the address keeps the read latency at one
// cycle, so this is interface-compatible with the SyncReadMem it replaces.
// Both ports are READ_FIRST; DtcmRam never issues both ports at the same row in
// the same cycle (see `sameRow`), so no BRAM collision is possible.
class DtcmBank(depth: Int, dataBits: Int) extends BlackBox(Map(
    "DEPTH"      -> IntParam(depth),
    "ADDR_WIDTH" -> IntParam(log2Ceil(depth)),
    "DATA_WIDTH" -> IntParam(dataBits),
)) with HasBlackBoxInline {
    require(depth >= 2, s"a DTCM bank needs at least two rows, got $depth")
    require(dataBits % 8 == 0, s"DTCM bank width must be a whole number of bytes")
    val addrBits = log2Ceil(depth)
    val strbBits = dataBits / 8

    // Instantiate under the name the hand-written source actually declares; the
    // Chisel class name would otherwise become the module name.
    override def desiredName = "xnpu_dtcm_bank"

    val io = IO(new Bundle {
        val clk     = Input(Clock())
        val a_en    = Input(Bool())
        val a_we    = Input(Bool())
        val a_wstrb = Input(UInt(strbBits.W))
        val a_addr  = Input(UInt(addrBits.W))
        val a_wdata = Input(UInt(dataBits.W))
        val a_rdata = Output(UInt(dataBits.W))
        val b_en    = Input(Bool())
        val b_we    = Input(Bool())
        val b_wstrb = Input(UInt(strbBits.W))
        val b_addr  = Input(UInt(addrBits.W))
        val b_wdata = Input(UInt(dataBits.W))
        val b_rdata = Output(UInt(dataBits.W))
    })

    setInline("xnpu_dtcm_bank.v",
        """// Copyright 2026 BUPT
          |//
          |// Byte-enabled true dual-port RAM, one clock, registered read data.
          |// This is the Xilinx UG901 true-dual-port template: one always block per
          |// port, write-enable per byte lane, READ_FIRST. Generated by Chisel as a
          |// BlackBox (see DtcmBank in src/main/scala/Dtcm.scala) because Vivado does
          |// not infer block RAM from firtool's two-write-port memory output.
          |module xnpu_dtcm_bank #(
          |    parameter integer DEPTH      = 1024,
          |    parameter integer ADDR_WIDTH = 10,
          |    parameter integer DATA_WIDTH = 128
          |) (
          |    input  wire                    clk,
          |    input  wire                    a_en,
          |    input  wire                    a_we,
          |    input  wire [DATA_WIDTH/8-1:0] a_wstrb,
          |    input  wire [ADDR_WIDTH-1:0]   a_addr,
          |    input  wire [DATA_WIDTH-1:0]   a_wdata,
          |    output reg  [DATA_WIDTH-1:0]   a_rdata,
          |    input  wire                    b_en,
          |    input  wire                    b_we,
          |    input  wire [DATA_WIDTH/8-1:0] b_wstrb,
          |    input  wire [ADDR_WIDTH-1:0]   b_addr,
          |    input  wire [DATA_WIDTH-1:0]   b_wdata,
          |    output reg  [DATA_WIDTH-1:0]   b_rdata
          |);
          |    (* ram_style = "block" *)
          |    reg [DATA_WIDTH-1:0] mem [0:DEPTH-1];
          |
          |    // Separate loop variables: a single module-scope integer shared by two
          |    // always blocks is a simulation race.
          |    integer ia;
          |    integer ib;
          |
          |    always @(posedge clk) begin
          |        if (a_en) begin
          |            for (ia = 0; ia < DATA_WIDTH/8; ia = ia + 1) begin
          |                if (a_we && a_wstrb[ia])
          |                    mem[a_addr][8*ia +: 8] <= a_wdata[8*ia +: 8];
          |            end
          |            a_rdata <= mem[a_addr];
          |        end
          |    end
          |
          |    always @(posedge clk) begin
          |        if (b_en) begin
          |            for (ib = 0; ib < DATA_WIDTH/8; ib = ib + 1) begin
          |                if (b_we && b_wstrb[ib])
          |                    mem[b_addr][8*ib +: 8] <= b_wdata[8*ib +: 8];
          |            end
          |            b_rdata <= mem[b_addr];
          |        end
          |    end
          |endmodule
          |""".stripMargin)
}


// Wide DTCM backing store. A true dual-port synchronous RAM of DtcmRowBytes-wide
// rows (one physical row = WordsPerRow 32-bit words = 128 bits) serves:
//
//   * Matrix on a dedicated wide port;
//   * Vector/Mem and DMA on an auxiliary wide port;
//   * the AXI host's 32-bit single-word view while idle.
//
// Word W lives in row W>>log2(WordsPerRow), lane W%WordsPerRow, so a host
// single-word write and a matrix full-row read address exactly the same bytes.
// A same-row request across the two physical ports is explicitly serialized with
// Matrix priority. This avoids relying on BRAM read-during-write behaviour.
class DtcmRam(p: Parameters, rows: Int, bankRows: Int = 1024) extends Module {
    val rowBytes    = p.DtcmRowBytes              // 16
    val rowWords    = p.WordsPerRow               // 4
    val rowAddrBits = log2Up(rows)
    val laneBits    = log2Up(rowWords)            // 2
    val rowShift    = log2Up(rowBytes)            // 4: byte address -> row index

    val io = IO(new Bundle {
        val busy = Input(Bool())

        // Matrix wide port. Flipped so the RAM
        // receives valid/write/addr/wdata/wstrb and drives ready/rdata.
        val matrix = Flipped(new DtcmPortIO(p))

        // Vector/Mem wide port. DMA arbitrates onto this physical port.
        val aux = Flipped(new DtcmPortIO(p))

        // DMA wide port, lower priority than the core auxiliary client.
        val dmaActive = Input(Bool())
        val dma       = Flipped(new DtcmPortIO(p))

        // Host 32-bit single-word view (used while idle).
        val hostEn    = Input(Bool())
        val hostWrite = Input(Bool())
        val hostAddr  = Input(UInt(p.AddrBits.W))
        val hostWdata = Input(UInt(32.W))
        val hostWstrb = Input(UInt(4.W))
        val hostRdata = Output(UInt(32.W))
    })

    // Bank by the high row-address bits. 1024 rows per bank is not arbitrary: a
    // RAMB36 in true-dual-port mode is 1024 x 36, so a 1024 x 128 bank is exactly
    // four RAMB36 side by side with byte enables on both ports and no depth
    // expansion. The production DTCM is therefore 32 banks = 128 RAMB36. It also
    // keeps each generated Verilog memory variable well under Vivado's 1 Mi-bit
    // per-variable limit, which a single 32768 x 128 array would blow past.
    require(bankRows >= 2 && rows >= bankRows && rows % bankRows == 0,
        s"DTCM rows ($rows) must be a multiple of bankRows ($bankRows), with at least two rows per bank")
    val bankCount = rows / bankRows
    val bankAddrBits = log2Ceil(bankRows)
    val memBanks = Seq.fill(bankCount)(Module(new DtcmBank(bankRows, p.DtcmRowBits)))

    val matRow   = (io.matrix.addr >> rowShift)(rowAddrBits - 1, 0)
    val auxRow   = (io.aux.addr >> rowShift)(rowAddrBits - 1, 0)
    val dmaRow   = (io.dma.addr >> rowShift)(rowAddrBits - 1, 0)
    val hostRow  = (io.hostAddr >> rowShift)(rowAddrBits - 1, 0)
    val hostLane = (io.hostAddr >> 2)(laneBits - 1, 0)

    // Port 0 is Matrix. Port 1 is Vector/Mem, with DMA taking it only when the
    // core auxiliary client is idle. The host is accepted only when both owners
    // are inactive (Npu applies the corresponding AXI backpressure).
    val matReq = io.busy && io.matrix.valid
    val auxCoreReq = io.busy && io.aux.valid
    val dmaReq = io.dmaActive && io.dma.valid
    val useDma = dmaReq && !auxCoreReq
    val auxReq = auxCoreReq || useDma
    val auxRowSel = Mux(useDma, dmaRow, auxRow)
    val sameRow = matReq && auxReq && matRow === auxRowSel
    val useMat = matReq
    val useAux = auxReq && !sameRow
    val useHost = io.hostEn && !io.busy && !io.dmaActive

    // Matrix owns port 0 on a collision; only the later Aux/DMA request waits.
    io.matrix.ready := true.B
    io.aux.ready := auxCoreReq && !sameRow
    io.dma.ready := useDma && !sameRow

    val auxWrite = Mux(useDma, io.dma.write, io.aux.write)
    val auxWdata = Mux(useDma, io.dma.wdata, io.aux.wdata)
    val auxWstrb = Mux(useDma, io.dma.wstrb, io.aux.wstrb)
    val auxActive = useAux || useHost
    val auxIsWrite = Mux(useAux, auxWrite, io.hostWrite)
    val auxMemRow = Mux(useAux, auxRowSel, hostRow)

    def rowBank(row: UInt): UInt = row(rowAddrBits - 1, bankAddrBits)
    def rowIndex(row: UInt): UInt = row(bankAddrBits - 1, 0)

    val matBank = rowBank(matRow)
    val auxBank = rowBank(auxMemRow)
    val matIndex = rowIndex(matRow)
    val auxIndex = rowIndex(auxMemRow)

    // Host writes one 32-bit word into its lane; only those 4 bytes are enabled.
    val hostWideWdata = Fill(rowWords, io.hostWdata)
    val hostStrb = Wire(Vec(rowBytes, Bool()))
    for (b <- 0 until rowBytes) {
        val lane       = b / 4
        val byteInWord = b % 4
        hostStrb(b) := (lane.U === hostLane) && io.hostWstrb(byteInWord)
    }

    val auxWriteData = Mux(useAux, auxWdata, hostWideWdata)
    val auxWriteStrb = Mux(useAux, auxWstrb, hostStrb.asUInt)

    for ((bank, index) <- memBanks.zipWithIndex) {
        bank.io.clk     := clock
        bank.io.a_en    := useMat && matBank === index.U
        bank.io.a_we    := io.matrix.write
        bank.io.a_wstrb := io.matrix.wstrb
        bank.io.a_addr  := matIndex
        bank.io.a_wdata := io.matrix.wdata
        bank.io.b_en    := auxActive && auxBank === index.U
        bank.io.b_we    := auxIsWrite
        bank.io.b_wstrb := auxWriteStrb
        bank.io.b_addr  := auxIndex
        bank.io.b_wdata := auxWriteData
    }

    // Bank read data arrives one cycle after the request, so the output mux must
    // be driven by the bank index of the access that *issued* the read, not by
    // whatever address the port happens to present now. Selecting on the live
    // index returns the wrong bank whenever consecutive accesses land in
    // different banks -- which a MATMUL does on every operand beat, since it
    // alternates between the A and B tiles.
    val matBankReg = RegNext(matBank)
    val auxBankReg = RegNext(auxBank)
    val matRrow = MuxLookup(matBankReg, 0.U(p.DtcmRowBits.W))(
        memBanks.zipWithIndex.map { case (bank, index) => index.U -> bank.io.a_rdata })
    val auxRrow = MuxLookup(auxBankReg, 0.U(p.DtcmRowBits.W))(
        memBanks.zipWithIndex.map { case (bank, index) => index.U -> bank.io.b_rdata })
    io.matrix.rdata := matRrow
    io.aux.rdata := auxRrow
    io.dma.rdata := auxRrow

    val hostLaneReg = RegNext(hostLane)
    val rwords = VecInit(Seq.tabulate(rowWords)(w => auxRrow(32 * w + 31, 32 * w)))
    io.hostRdata := rwords(hostLaneReg)
}
